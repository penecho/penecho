// npm run build:lines builds the bundles from the files in this folder, npm run check:lines says whether they are up to date.
// The folder can hold other work that is not in your commit, and a bundle built from it would carry that along. So a commit that
// changes a Lines page takes its bundles from what is staged: git add your files, then npm run build:lines -- --staged.
// -- --check --staged and -- --check --ref <commit> check the bundles of what is staged, or of a commit, against its own sources.

