#!/usr/bin/env python3
"""Build native plugin/Skill archives and a separate Hermes compatibility plugin."""
from pathlib import Path
import json
import zipfile

ROOT = Path(__file__).resolve().parents[1]
PLUGIN = ROOT / "integrations/penecho-cloud"
SKILL = PLUGIN / "skills/penecho-canvas"
HERMES = PLUGIN / "hermes/portable"
# Explicit allowlists avoid distributing credentials, historical submissions or build output.
PLUGIN_FILES = (
    ".claude-plugin/plugin.json", ".codex-plugin/plugin.json", ".cursor-plugin/plugin.json",
    ".mcp.json", "plugin.json", "mcp.json", "server.json", "README.md", "INSTALL.md", "LICENSE",
    "assets/logo.png",
)
SKILL_FILES = ("SKILL.md", "agents/openai.yaml", "references/mcp.json", "scripts/setup-mcp.mjs", "scripts/install.mjs")
HERMES_FILES = ("plugin.json", "mcp.json", "README.md", "LICENSE", "assets/logo.png")
HERMES_MCP = {
    "$schema": "https://agent-plugins.org/schemas/1.0.0/mcp.schema.json",
    "mcpServers": {"penecho-cloud": {
        "type": "stdio", "command": "npx",
        "args": ["-y", "mcp-remote@0.1.38", "https://penecho.ai/mcp",
                 "--transport", "http-only", "--resource", "https://penecho.ai/mcp"],
    }},
}
HERMES_README = """# PenEcho Hermes compatibility plugin

This generated variant is for the Hermes portable loader's stdio compatibility path.
Install this directory or extract `penecho-hermes-plugin.zip`; select this connection
instead of the native Hermes MCP catalog connection to avoid duplicates. It uses
Node.js 20+/npx and pinned `mcp-remote@0.1.38` for OAuth to `https://penecho.ai/mcp`.
Complete normal host OAuth authorization. Credentials belong in the host's
credential store and are never bundled here.

The main Codex, Claude and Cursor distribution uses native HTTPS. Use
`integrations/penecho-cloud` or `penecho-cloud-plugin.zip` for those hosts.
This directory is generated by `python3 scripts/package-penecho-cloud.py` from the
canonical manifest, license, assets and `skills/penecho-canvas/` source. Edit that
source and rebuild; do not maintain a second workflow Skill here. Package version
matches the main native distribution. Local generation does not prove publication
or a successful fresh-host installation.
"""


def read_source(source):
    if source.is_symlink() or not source.is_file():
        raise ValueError(f"Missing or symlinked distribution source: {source.relative_to(ROOT)}")
    return source.read_bytes()


def write_archive(destination, entries):
    with zipfile.ZipFile(destination, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        for source, name in sorted(entries, key=lambda entry: entry[1]):
            info = zipfile.ZipInfo(name, date_time=(2026, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o100644 << 16
            archive.writestr(info, read_source(source))


def sync_hermes(manifest):
    """Synchronize generated compatibility files without copying unrelated output."""
    payloads = {
        "plugin.json": (json.dumps(manifest, indent=2) + "\n").encode(),
        "mcp.json": (json.dumps(HERMES_MCP, indent=2) + "\n").encode(),
        "README.md": HERMES_README.encode(),
    }
    for relative in ("LICENSE", "assets/logo.png"):
        payloads[relative] = read_source(PLUGIN / relative)
    for relative in SKILL_FILES:
        payloads[f"skills/penecho-canvas/{relative}"] = read_source(SKILL / relative)
    for relative, content in payloads.items():
        destination = HERMES / relative
        if destination.is_symlink() or any(parent.is_symlink() for parent in destination.parents if parent != ROOT):
            raise ValueError(f"Symlinked generated compatibility destination: {destination}")
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes(content)


def build():
    manifest = json.loads(read_source(PLUGIN / "plugin.json"))
    for relative in (".claude-plugin/plugin.json", ".codex-plugin/plugin.json", ".cursor-plugin/plugin.json", "server.json", "hermes/catalog-entry.json"):
        if json.loads(read_source(PLUGIN / relative))["version"] != manifest["version"]:
            raise ValueError(f"Version mismatch: {relative}")
    sync_hermes(manifest)
    skill_entries = [(SKILL / relative, f"penecho-canvas/{relative}") for relative in SKILL_FILES]
    plugin_entries = [(PLUGIN / relative, f"penecho-cloud/{relative}") for relative in PLUGIN_FILES]
    plugin_entries += [(source, f"penecho-cloud/skills/{name}") for source, name in skill_entries]
    hermes_entries = [(HERMES / relative, f"penecho-cloud/{relative}") for relative in HERMES_FILES]
    hermes_entries += [(HERMES / "skills" / name, f"penecho-cloud/skills/{name}") for _, name in skill_entries]
    destinations = (PLUGIN / "penecho-canvas.zip", PLUGIN / "penecho-cloud-plugin.zip", PLUGIN / "penecho-hermes-plugin.zip")
    for destination, entries in zip(destinations, (skill_entries, plugin_entries, hermes_entries)):
        write_archive(destination, entries)
    # Native account upload artifact; retain the established three-archive return API.
    (PLUGIN / "penecho-cloud.plugin").write_bytes(destinations[1].read_bytes())
    return destinations


if __name__ == "__main__":
    for destination in build():
        print(destination)
